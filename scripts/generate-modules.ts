import fs from "node:fs";
import path from "node:path";

const root = path.join(process.cwd(), "challenges");
const target = path.join(process.cwd(), "lib", "challenges", "modules.ts");

function directories(): string[] {
  if (!fs.existsSync(root)) return [];
  return fs
    .readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .flatMap((theme) =>
      fs
        .readdirSync(path.join(root, theme.name), { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => path.join(theme.name, entry.name)),
    )
    .sort();
}

const identifier = (directory: string) =>
  directory.replace(/[^a-zA-Z0-9]+/g, "_");

/**
 * The challenge loader has to import the generator and the reference solver
 * as real modules so the bundler can include them. This script keeps that
 * static import list in step with the challenges directory, so publishing a
 * new challenge never depends on remembering to edit a second file.
 */
function main() {
  const found = directories();

  const imports = found
    .map(
      (directory) =>
        `import * as ${identifier(directory)}Generator from "../../challenges/${directory}/generator";
import * as ${identifier(directory)}Solver from "../../challenges/${directory}/reference-solution";`,
    )
    .join("\n");

  const entries = found
    .map(
      (directory) => `  "${directory}": {
    generator: ${identifier(directory)}Generator,
    solver: ${identifier(directory)}Solver,
  },`,
    )
    .join("\n");

  const contents = `import type { DeterministicRng } from "@/lib/rng";

import type { GeneratedChallengeInput } from "./types";
${imports}

type ChallengeModules = {
  generator: { generate(rng: DeterministicRng): GeneratedChallengeInput };
  solver: { solve(value: unknown): string };
};

/**
 * Generated by \`pnpm run challenges:manifest\`. Do not edit by hand.
 */
const challengeModules: Record<string, ChallengeModules> = {
${entries}
};

export function getChallengeModules(
  relativeDirectory: string,
): ChallengeModules {
  const modules = challengeModules[relativeDirectory];
  if (!modules)
    throw new Error(
      \`Challenge \${relativeDirectory} is missing from lib/challenges/modules.ts. Run "pnpm run challenges:manifest".\`,
    );
  return modules;
}
`;

  const previous = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (previous === contents) {
    console.log(`Module manifest already up to date (${found.length}).`);
    return;
  }
  fs.writeFileSync(target, contents);
  console.log(
    `Wrote lib/challenges/modules.ts with ${found.length} challenge(s).`,
  );
}

main();
